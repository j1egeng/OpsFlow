-- OpsFlow initial schema for PostgreSQL. Flyway executes this migration transactionally.
-- Business lifecycle transitions and actor permissions are enforced by the application.

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    description TEXT,
    CONSTRAINT ck_roles_code CHECK (code IN ('ADMINISTRATOR', 'DEVELOPER', 'APPROVER')),
    CONSTRAINT ck_roles_name CHECK (btrim(name) <> '')
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(254) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_users_username CHECK (username = btrim(username) AND username <> ''),
    CONSTRAINT ck_users_email CHECK (email = btrim(email) AND email <> ''),
    CONSTRAINT ck_users_display_name CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_users_password_hash CHECK (btrim(password_hash) <> ''),
    CONSTRAINT ck_users_version CHECK (version >= 0)
);
CREATE UNIQUE INDEX uq_users_username_ci ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email_ci ON users (lower(email));

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users(id),
    role_id BIGINT NOT NULL REFERENCES roles(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_by BIGINT REFERENCES users(id),
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX idx_user_roles_role ON user_roles (role_id);
CREATE INDEX idx_user_roles_assigned_by ON user_roles (assigned_by);

CREATE TABLE software_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    owner_id BIGINT REFERENCES users(id),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_software_services_code CHECK (code = btrim(code) AND code <> ''),
    CONSTRAINT ck_software_services_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_software_services_version CHECK (version >= 0)
);
CREATE UNIQUE INDEX uq_software_services_code_ci ON software_services (lower(code));
CREATE INDEX idx_software_services_owner ON software_services (owner_id);
CREATE INDEX idx_software_services_created_by ON software_services (created_by);

CREATE TABLE incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES software_services(id),
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    assignee_id BIGINT REFERENCES users(id),
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    severity VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN',
    resolution TEXT,
    source_change_id BIGINT,
    resolved_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_incidents_id_service UNIQUE (id, service_id),
    CONSTRAINT uq_incidents_source_change UNIQUE (source_change_id),
    CONSTRAINT ck_incidents_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_incidents_description CHECK (btrim(description) <> ''),
    CONSTRAINT ck_incidents_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_incidents_status CHECK (status IN ('OPEN', 'ASSIGNED', 'INVESTIGATING', 'RESOLVED', 'CLOSED')),
    CONSTRAINT ck_incidents_assignment CHECK (
        (status = 'OPEN' AND assignee_id IS NULL)
        OR (status <> 'OPEN' AND assignee_id IS NOT NULL)
    ),
    CONSTRAINT ck_incidents_resolution CHECK (
        status NOT IN ('RESOLVED', 'CLOSED')
        OR (resolution IS NOT NULL AND btrim(resolution) <> '')
    ),
    CONSTRAINT ck_incidents_resolved_at CHECK (
        (status IN ('RESOLVED', 'CLOSED')) = (resolved_at IS NOT NULL)
    ),
    CONSTRAINT ck_incidents_closed_at CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CONSTRAINT ck_incidents_time_order CHECK (
        (resolved_at IS NULL OR resolved_at >= created_at)
        AND (closed_at IS NULL OR closed_at >= resolved_at)
    ),
    CONSTRAINT ck_incidents_version CHECK (version >= 0)
);
CREATE INDEX idx_incidents_service_status ON incidents (service_id, status);
CREATE INDEX idx_incidents_status_created ON incidents (status, created_at DESC);
CREATE INDEX idx_incidents_severity_created ON incidents (severity, created_at DESC);
CREATE INDEX idx_incidents_assignee_status ON incidents (assignee_id, status);
CREATE INDEX idx_incidents_reporter ON incidents (reporter_id);

CREATE TABLE incident_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    author_id BIGINT NOT NULL REFERENCES users(id),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_incident_notes_content CHECK (btrim(content) <> '')
);
CREATE INDEX idx_incident_notes_timeline ON incident_notes (incident_id, created_at, id);
CREATE INDEX idx_incident_notes_author ON incident_notes (author_id);

CREATE TABLE incident_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id BIGINT NOT NULL REFERENCES incidents(id),
    old_status VARCHAR(24),
    new_status VARCHAR(24) NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES users(id),
    comment TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_incident_history_old_status CHECK (
        old_status IS NULL OR old_status IN ('OPEN', 'ASSIGNED', 'INVESTIGATING', 'RESOLVED', 'CLOSED')
    ),
    CONSTRAINT ck_incident_history_new_status CHECK (
        new_status IN ('OPEN', 'ASSIGNED', 'INVESTIGATING', 'RESOLVED', 'CLOSED')
    ),
    CONSTRAINT ck_incident_history_changed CHECK (old_status IS NULL OR old_status <> new_status)
);
CREATE INDEX idx_incident_history_timeline ON incident_status_history (incident_id, changed_at, id);
CREATE INDEX idx_incident_history_actor ON incident_status_history (changed_by);

CREATE TABLE change_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES software_services(id),
    requester_id BIGINT NOT NULL REFERENCES users(id),
    related_incident_id BIGINT,
    title VARCHAR(200) NOT NULL,
    business_reason TEXT,
    risk_level VARCHAR(16),
    planned_implementation_at TIMESTAMPTZ,
    implementation_plan TEXT,
    rollback_plan TEXT,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT',
    submission_number INTEGER NOT NULL DEFAULT 0,
    submitted_at TIMESTAMPTZ,
    implementation_started_at TIMESTAMPTZ,
    implementation_finished_at TIMESTAMPTZ,
    implementation_result TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_change_requests_id_service UNIQUE (id, service_id),
    CONSTRAINT fk_change_requests_related_incident FOREIGN KEY (related_incident_id, service_id)
        REFERENCES incidents(id, service_id),
    CONSTRAINT ck_change_requests_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_change_requests_risk CHECK (risk_level IS NULL OR risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_change_requests_status CHECK (
        status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'IMPLEMENTING', 'COMPLETED', 'FAILED')
    ),
    CONSTRAINT ck_change_requests_submission_number CHECK (submission_number >= 0),
    CONSTRAINT ck_change_requests_submission CHECK (
        status = 'DRAFT' OR (
            submission_number > 0 AND submitted_at IS NOT NULL
            AND business_reason IS NOT NULL AND btrim(business_reason) <> ''
            AND risk_level IS NOT NULL AND planned_implementation_at IS NOT NULL
            AND implementation_plan IS NOT NULL AND btrim(implementation_plan) <> ''
            AND rollback_plan IS NOT NULL AND btrim(rollback_plan) <> ''
        )
    ),
    CONSTRAINT ck_change_requests_started CHECK (
        (status IN ('IMPLEMENTING', 'COMPLETED', 'FAILED')) = (implementation_started_at IS NOT NULL)
    ),
    CONSTRAINT ck_change_requests_finished CHECK (
        (status IN ('COMPLETED', 'FAILED')) = (implementation_finished_at IS NOT NULL)
    ),
    CONSTRAINT ck_change_requests_result CHECK (
        status NOT IN ('COMPLETED', 'FAILED')
        OR (implementation_result IS NOT NULL AND btrim(implementation_result) <> '')
    ),
    CONSTRAINT ck_change_requests_time_order CHECK (
        (submitted_at IS NULL OR submitted_at >= created_at)
        AND (implementation_started_at IS NULL OR implementation_started_at >= submitted_at)
        AND (implementation_finished_at IS NULL OR implementation_finished_at >= implementation_started_at)
    ),
    CONSTRAINT ck_change_requests_version CHECK (version >= 0)
);
CREATE INDEX idx_change_requests_service_status ON change_requests (service_id, status);
CREATE INDEX idx_change_requests_status_created ON change_requests (status, created_at DESC);
CREATE INDEX idx_change_requests_requester ON change_requests (requester_id);
CREATE INDEX idx_change_requests_related_incident ON change_requests (related_incident_id, service_id);

ALTER TABLE incidents ADD CONSTRAINT fk_incidents_source_change
    FOREIGN KEY (source_change_id, service_id) REFERENCES change_requests(id, service_id);

CREATE TABLE change_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_request_id BIGINT NOT NULL REFERENCES change_requests(id),
    submission_number INTEGER NOT NULL,
    reviewer_id BIGINT NOT NULL REFERENCES users(id),
    decision VARCHAR(16) NOT NULL,
    comment TEXT,
    reviewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_change_reviews_submission UNIQUE (change_request_id, submission_number),
    CONSTRAINT ck_change_reviews_submission CHECK (submission_number > 0),
    CONSTRAINT ck_change_reviews_decision CHECK (decision IN ('APPROVED', 'REJECTED')),
    CONSTRAINT ck_change_reviews_rejection_comment CHECK (
        decision <> 'REJECTED' OR (comment IS NOT NULL AND btrim(comment) <> '')
    )
);
CREATE INDEX idx_change_reviews_reviewer ON change_reviews (reviewer_id);

CREATE TABLE change_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    change_request_id BIGINT NOT NULL REFERENCES change_requests(id),
    old_status VARCHAR(24),
    new_status VARCHAR(24) NOT NULL,
    changed_by BIGINT NOT NULL REFERENCES users(id),
    comment TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_change_history_old_status CHECK (
        old_status IS NULL OR old_status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'IMPLEMENTING', 'COMPLETED', 'FAILED')
    ),
    CONSTRAINT ck_change_history_new_status CHECK (
        new_status IN ('DRAFT', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'IMPLEMENTING', 'COMPLETED', 'FAILED')
    ),
    CONSTRAINT ck_change_history_changed CHECK (old_status IS NULL OR old_status <> new_status)
);
CREATE INDEX idx_change_history_timeline ON change_status_history (change_request_id, changed_at, id);
CREATE INDEX idx_change_history_actor ON change_status_history (changed_by);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES users(id),
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    request_id UUID,
    client_ip INET,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_audit_logs_action CHECK (btrim(action) <> ''),
    CONSTRAINT ck_audit_logs_entity_type CHECK (entity_type IN ('USER', 'ROLE', 'SERVICE', 'INCIDENT', 'CHANGE_REQUEST')),
    CONSTRAINT ck_audit_logs_entity_id CHECK (entity_id > 0),
    CONSTRAINT ck_audit_logs_details_object CHECK (jsonb_typeof(details) = 'object')
);
CREATE INDEX idx_audit_logs_entity_timeline ON audit_logs (entity_type, entity_id, occurred_at DESC, id);
CREATE INDEX idx_audit_logs_actor_timeline ON audit_logs (actor_id, occurred_at DESC);
CREATE INDEX idx_audit_logs_occurred ON audit_logs (occurred_at DESC);

CREATE FUNCTION opsflow_set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION opsflow_set_updated_at();
CREATE TRIGGER trg_software_services_updated_at BEFORE UPDATE ON software_services
    FOR EACH ROW EXECUTE FUNCTION opsflow_set_updated_at();
CREATE TRIGGER trg_incidents_updated_at BEFORE UPDATE ON incidents
    FOR EACH ROW EXECUTE FUNCTION opsflow_set_updated_at();
CREATE TRIGGER trg_change_requests_updated_at BEFORE UPDATE ON change_requests
    FOR EACH ROW EXECUTE FUNCTION opsflow_set_updated_at();

COMMENT ON TABLE roles IS 'Supported application roles; separate from PostgreSQL database roles.';
COMMENT ON TABLE users IS 'Application users. Store encoded password hashes only; disable accounts instead of deleting history.';
COMMENT ON TABLE user_roles IS 'Many-to-many application role assignments.';
COMMENT ON TABLE software_services IS 'Managed software services and their responsible owners.';
COMMENT ON TABLE incidents IS 'Incident lifecycle, assignment, resolution and optional originating failed change.';
COMMENT ON TABLE incident_notes IS 'Append-only investigation notes written by users.';
COMMENT ON TABLE incident_status_history IS 'Incident status history written in the same transaction as the status change.';
COMMENT ON TABLE change_requests IS 'Change drafts, submission rounds, risk/plans and implementation outcomes.';
COMMENT ON TABLE change_reviews IS 'One approval/rejection decision per change submission round.';
COMMENT ON TABLE change_status_history IS 'Change lifecycle history written in the same transaction as the status change.';
COMMENT ON TABLE audit_logs IS 'Application audit events; never store passwords or access tokens in details.';
COMMENT ON COLUMN incidents.source_change_id IS 'One incident per originating failed change; service must match. FAILED status is validated by the application.';
COMMENT ON COLUMN change_requests.related_incident_id IS 'Optional pre-existing incident motivating this change; service must match.';
COMMENT ON COLUMN audit_logs.entity_id IS 'Polymorphic entity reference. The application validates entity existence.';
