  await dialog.locator('textarea[name="implementationPlan"]').fill('Apply new configuration')
  await dialog.locator('textarea[name="rollbackPlan"]').fill('Restore old configuration')
  const related = dialog.locator('#incident-related')
  await expect(related).toBeEnabled()
