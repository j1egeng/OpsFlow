test('multi-role requester cannot self-approve and approver has no create control', async ({ page }) => {
  await login(page, 'dualrole')
  const created = await page.evaluate(async () => {
    const session = JSON.parse(sessionStorage.getItem('opsflow.session.v1') || '{}')
    const headers = { Authorization: `Bearer ${session.token}`, 'Content-Type': 'application/json' }
    const body = { serviceId: 1, title: 'Self review guard', businessReason: 'Test roles', riskLevel: 'LOW', plannedImplementationAt: new Date(Date.now() + 86400000).toISOString(), implementationPlan: 'Implement', rollbackPlan: 'Rollback' }
    const draft = await (await fetch('/api/v1/changes', { method: 'POST', headers, body: JSON.stringify(body) })).json()
    return (await fetch(`/api/v1/changes/${draft.id}/submit`, { method: 'POST', headers, body: JSON.stringify({ version: draft.version }) })).json()
  })
  await page.goto(`/changes/${created.id}`)
  await expect(page.locator('.incident-detail-title')).toContainText('Pending approval')
  await expect(page.getByRole('button', { name: 'Approve change', exact: true })).toHaveCount(0)
  const status = await page.evaluate(async change => {
    const session = JSON.parse(sessionStorage.getItem('opsflow.session.v1') || '{}')
    return (await fetch(`/api/v1/changes/${change.id}/reviews`, { method: 'POST', headers: { Authorization: `Bearer ${session.token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ version: change.version, decision: 'APPROVED' }) })).status
  }, created)
  expect(status).toBe(403)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await login(page, 'approver', `/changes/${created.id}`)
  await changes(page)
  await expect(page.getByRole('button', { name: 'New change', exact: true })).toHaveCount(0)
})

test('filters, paging and stale draft conflicts preserve saved data', async ({ page, context }) => {
  await login(page, 'developer')
  await changes(page)
  await page.getByRole('button', { name: 'Next page', exact: true }).click()
  await expect(page.getByText('Page 2 of 2', { exact: true })).toBeVisible()
  await page.getByLabel('Change status', { exact: true }).selectOption('FAILED')
  await expect(page.getByRole('table', { name: 'Change list' })).toContainText('Seed change 06')
  await page.getByLabel('Risk level', { exact: true }).selectOption('HIGH')
  await expect(page.getByRole('heading', { name: 'No matching changes' })).toBeVisible()
  await seed(page, 'Seed change 07')
  const path = new URL(page.url()).pathname
  await page.getByRole('button', { name: 'Edit change draft', exact: true }).click()
  const session = await page.evaluate(() => sessionStorage.getItem('opsflow.session.v1'))
  const second = await context.newPage()
  await second.goto('/login'); await second.evaluate(value => sessionStorage.setItem('opsflow.session.v1', value!), session)
  await second.goto(path)
  await second.getByRole('button', { name: 'Edit change draft', exact: true }).click()
  await second.getByRole('dialog').locator('input[name="title"]').fill('Concurrent saved title')
  await second.getByRole('dialog').getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(second.getByRole('dialog')).not.toBeVisible()
  const dialog = page.getByRole('dialog')
  await dialog.locator('input[name="title"]').fill('Stale title')
  await dialog.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('The record has changed.')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Refresh details', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Concurrent saved title' })).toBeVisible()
  await second.close()
})

