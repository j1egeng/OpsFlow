import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const language = (page: Page) => page.locator('dialog[open] select[aria-label="界面语言 / Interface language"], body:not(:has(dialog[open])) select[aria-label="界面语言 / Interface language"]')
async function login(page: Page, username = 'browseradmin', returnPath?: string) {
  await page.goto('/login')
  await language(page).selectOption('en')
  await page.locator('input[name="username"]').fill(username)
  await page.locator('input[name="password"]').fill('BrowserTestPass123!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(returnPath ? new RegExp(`${returnPath}$`) : username === 'browseradmin' ? /\/users$/ : /\/account$/)
}
async function changes(page: Page) {
  await page.getByRole('navigation').getByRole('link', { name: 'Change management', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Change list' })).toBeVisible()
}
async function seed(page: Page, title: string) {
  await changes(page)
  await page.getByLabel('Change status', { exact: true }).selectOption('')
  await page.getByLabel('Risk level', { exact: true }).selectOption('')
  await page.getByLabel('Changes per page').selectOption('50')
  await page.getByRole('link', { name: title, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Change details', exact: true })).toBeVisible()
}
async function changeActor(page: Page, username: string, path: string) {
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await login(page, username, path)
  await page.goto(path)
  await expect(page.getByRole('heading', { name: 'Change details', exact: true })).toBeVisible()
}

