test('unassigned developer and approver cannot mutate another developer incident', async ({ page }) => {
  await login(page, 'developer')
  await seed(page, 'Seed incident 02')
  const returnPath = new URL(page.url()).pathname
  await expect(page.locator('.incident-actions button')).toHaveCount(0)
  await expect(page.locator('textarea[name="note"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await login(page, 'approver', returnPath)
  await expect(page.getByRole('button', { name: 'Report incident', exact: true })).toHaveCount(0)
  await seed(page, 'Seed incident 01')
  await expect(page.locator('.incident-actions button')).toHaveCount(0)
  await expect(page.locator('textarea[name="note"]')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Status history' })).toBeVisible()
})

test('stale incident details cannot overwrite updates from another browser tab', async ({ page, context }) => {
  await login(page)
  await seed(page, 'Seed incident 03')
  const id = Number(page.url().split('/').at(-1))
  const session = await page.evaluate(() => sessionStorage.getItem('opsflow.session.v1'))
  const second = await context.newPage()
  await second.goto('/login')
  await second.evaluate(value => sessionStorage.setItem('opsflow.session.v1', value!), session)
  await second.goto(`/incidents/${id}`)
  await second.getByRole('button', { name: 'Assign incident', exact: true }).click()
  const secondDialog = second.getByRole('dialog')
  await expect(secondDialog.locator('#incident-assignee')).toBeEnabled()
  const option = secondDialog.locator('#incident-assignee option').filter({ hasText: '@developer' })
  await secondDialog.locator('#incident-assignee').selectOption(await option.getAttribute('value') || '')
  await secondDialog.getByRole('button', { name: 'Assign incident', exact: true }).click()
  await expect(secondDialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Assign incident', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('#incident-assignee')).toBeEnabled()
  const adminOption = dialog.locator('#incident-assignee option').filter({ hasText: '@browseradmin' })
  await dialog.locator('#incident-assignee').selectOption(await adminOption.getAttribute('value') || '')
  await dialog.getByRole('button', { name: 'Assign incident', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('The record has changed.')
  await expect(dialog.getByRole('button', { name: 'Assign incident', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Refresh details', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reassign', exact: true })).toBeVisible()
  await second.close()
})

