import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const language = (page: Page) => page.locator('dialog[open] select[aria-label="界面语言 / Interface language"], body:not(:has(dialog[open])) select[aria-label="界面语言 / Interface language"]')
async function login(page: Page, username = 'browseradmin', returnPath?: string) {
  await page.goto('/login')
  await language(page).selectOption('en')
  await page.locator('input[name="username"]').fill(username)
  await page.locator('input[name="password"]').fill('BrowserTestPass123!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(returnPath ? new RegExp(`${returnPath}$`) : username === 'browseradmin' ? /\/users$/ : /\/account$/)
  await page.getByRole('navigation').getByRole('link', { name: 'Incident management', exact: true }).click()
  await expect(page.getByRole('table', { name: 'Incident list' })).toBeVisible()
}
async function seed(page: Page, name: string) {
  await page.getByLabel('Incidents per page').selectOption('50')
  await page.getByRole('link', { name, exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Incident details', exact: true })).toBeVisible()
}

test('administrator reports an incident and completes its lifecycle using real endpoints', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Report incident', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('#incident-service')).toBeEnabled()
  await expect(dialog.locator('#incident-service option').filter({ hasText: 'catalog-13' })).toHaveCount(0)
  await dialog.locator('#incident-service').selectOption({ label: 'Catalog service 1 (catalog-01)' })
  const title = `Payment timeout ${Date.now()}`
  await dialog.locator('input[name="title"]').fill(title)
  await dialog.locator('textarea[name="description"]').fill('Requests are failing in the payment service')
  await dialog.locator('select[name="severity"]').selectOption('CRITICAL')
  await language(page).selectOption('zh-CN')
  await expect(dialog.getByRole('heading', { name: '报告事件' })).toBeVisible()
  await expect(dialog.locator('input[name="title"]')).toHaveValue(title)
  await dialog.getByRole('button', { name: '提交事件', exact: true }).click()
  await expect(page).toHaveURL(/\/incidents\/\d+$/)
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await language(page).selectOption('en')
  await page.getByRole('button', { name: 'Assign incident', exact: true }).click()
  const assignee = dialog.locator('#incident-assignee')
  await expect(assignee).toBeEnabled()
  const option = assignee.getByRole('option').filter({ hasText: '@browseradmin' })
  await assignee.selectOption(await option.getAttribute('value') || '')
  await dialog.locator('textarea[name="comment"]').fill('Administrator will handle this incident')
  await dialog.getByRole('button', { name: 'Assign incident', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Start investigation', exact: true }).click()
  await dialog.getByRole('button', { name: 'Start investigation', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.locator('textarea[name="note"]').fill('Found an exhausted connection pool')
  await page.getByRole('button', { name: 'Add note', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Investigation notes' })).toContainText('Found an exhausted connection pool')
  await page.getByRole('button', { name: 'Resolve incident', exact: true }).click()
  await dialog.locator('textarea[name="resolution"]').fill('Adjusted the connection pool and verified recovery')
  await dialog.getByRole('button', { name: 'Resolve incident', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Close incident', exact: true }).click()
  await dialog.locator('textarea[name="comment"]').fill('Recovery confirmed')
  await dialog.getByRole('button', { name: 'Close incident', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.locator('.incident-detail-title')).toContainText('Closed')
  await expect(page.locator('.incident-resolution')).toContainText('Adjusted the connection pool')
  await expect(page.getByRole('region', { name: 'Status history' }).locator('li')).toHaveCount(5)
  await expect(page.locator('textarea[name="note"]')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.incident-detail-title')).toContainText('Closed')
})

