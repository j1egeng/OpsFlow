import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const language = (page: Page) => page.locator('dialog[open] select[aria-label="界面语言 / Interface language"], body:not(:has(dialog[open])) select[aria-label="界面语言 / Interface language"]')
async function login(page: Page, username = 'browseradmin', english = false) {
  await page.goto('/login')
  if (english) await language(page).selectOption('en')
  await page.locator('input[name="username"]').fill(username)
  await page.locator('input[name="password"]').fill('BrowserTestPass123!')
  await page.getByRole('button', { name: english ? 'Sign in' : '登录工作台', exact: true }).click()
  await expect(page).toHaveURL(username === 'browseradmin' ? /\/users$/ : /\/account$/)
}
async function services(page: Page, english = false) {
  await page.getByRole('navigation').getByRole('link', { name: english ? 'Service management' : '服务管理', exact: true }).click()
  await expect(page.getByRole('table', { name: english ? 'Service list' : '服务列表' })).toBeVisible()
}

test('language switches immediately, persists after reload, and leaves login input intact', async ({ page }) => {
  await page.goto('/login')
  await page.locator('input[name="username"]').fill('my-draft-username')
  await language(page).selectOption('en')
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  await expect(page.locator('input[name="username"]')).toHaveValue('my-draft-username')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
  await language(page).selectOption('zh-CN')
  await expect(page.getByRole('heading', { name: '欢迎回来' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
})

