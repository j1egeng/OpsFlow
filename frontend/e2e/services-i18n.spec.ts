test('English desktop and mobile service pages have no overflow or runtime errors', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page, 'browseradmin', true)
  await services(page, true)
  await page.screenshot({ path: 'test-results/services-en-desktop.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'New service', exact: true }).click()
  await page.screenshot({ path: 'test-results/service-editor-en.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/services-en-mobile.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'New service', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await page.getByRole('link', { name: 'My account', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
