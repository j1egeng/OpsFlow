test('administrator creates and edits a service, selects an owner on another page, and toggles status', async ({ page }) => {
  await login(page)
  await services(page)
  await page.getByRole('button', { name: '新建服务', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const code = `e2e-${Date.now()}`
  await dialog.locator('input[name="code"]').fill(code.toUpperCase())
  await dialog.locator('input[name="name"]').fill('测试支付服务')
  await dialog.locator('textarea[name="description"]').fill('支付服务原始描述')
  await dialog.getByRole('button', { name: '下一批用户' }).click()
  const owner = dialog.locator('select[name="ownerId"]')
  const option = owner.getByRole('option').filter({ hasText: '@member13' })
  await expect(option).toHaveCount(1)
  await owner.selectOption(await option.getAttribute('value') || '')
  await language(page).selectOption('en')
  await expect(dialog.getByRole('heading', { name: 'New service' })).toBeVisible()
  await expect(dialog.locator('input[name="name"]')).toHaveValue('测试支付服务')
  await dialog.getByRole('button', { name: 'Create service', exact: true }).click()
  await expect(page).toHaveURL(/\/services\/\d+$/)
  await expect(page.getByRole('heading', { name: '测试支付服务' })).toBeVisible()
  await expect(page.getByText(/@member13/)).toBeVisible()
  await expect(page.getByText(code, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit service', exact: true }).click()
  await dialog.locator('input[name="name"]').fill('Updated payment service')
  await dialog.locator('textarea[name="description"]').fill('Updated description')
  await expect(dialog.locator('select[name="ownerId"] option:checked')).toContainText('@member13')
  await dialog.locator('select[name="ownerId"]').selectOption('')
  await dialog.getByRole('button', { name: 'Save service', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('heading', { name: 'Updated payment service' })).toBeVisible()
  await expect(page.getByText('Unassigned', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Disable service', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirm disable', exact: true }).click()
  await expect(page.locator('.service-detail-heading')).toContainText('Disabled')
  await page.getByRole('button', { name: 'Enable service', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirm enable', exact: true }).click()
  await expect(page.locator('.service-detail-heading')).toContainText('Enabled')
  await page.reload()
  await expect(page.getByText('Updated description', { exact: true })).toBeVisible()
})

